package eu.torvian.chatbot.common.models.agent

/**
 * Centralized constants for the well-known agent-instruction kind keys.
 *
 * The `instructions` list on [AgentInstructionDto] (via [eu.torvian.chatbot.common.models.agent.AgentRoleDto])
 * is a flat list identified by each entry's `type` field. Kind-specific extra fields (e.g.
 * `modelId` for `model_specific`) are carried in the `custom` JSON object of each entry.
 *
 * This mirrors the constants-object pattern used by `CommonUserGroups` and `CommonPermissions` so that
 * instruction-type strings stay typo-free and centralized across the shared API surface.
 */
object AgentInstructionTypes {

    /**
     * Static role description, e.g. "You are a senior software architect...".
     */
    const val ROLE: String = "role"

    /**
     * Project context, usually `AGENTS.md` content.
     */
    const val MAIN: String = "main"

    /**
     * User-editable free text.
     */
    const val CUSTOM: String = "custom"

    /**
     * Dynamic guidance describing the roles that the current role may spawn.
     *
     * The message is generated by the server from current role metadata; any client-supplied message
     * for this marker is ignored.
     */
    const val SPAWNABLE_AGENTS: String = "spawnable_agents"

    /**
     * Per-model instruction marker: applies only when the conversation is running on the model
     * referenced by `custom.modelId`. Multiple `model_specific` entries are allowed as long as each
     * targets a distinct model.
     */
    const val MODEL_SPECIFIC: String = "model_specific"

    /**
     * Dynamic guidance listing the credential profiles available to the current role.
     *
     * The message is generated by the server from current profile metadata; any client-supplied
     * message for this marker is ignored. At most one such row may exist per role, and its text is
     * never stored.
     */
    const val CREDENTIAL_PROFILES: String = "credential_profiles"

    /**
     * Every well-known instruction kind, in canonical display order.
     *
     * Used by server built-in tools and the catalog schemas to enumerate the accepted `type` values
     * (e.g. for validation error messages and JSON-Schema `enum` arrays) without repeating the
     * constants at each call site.
     */
    val allKnown: List<String> = listOf(
        ROLE,
        MAIN,
        CUSTOM,
        SPAWNABLE_AGENTS,
        CREDENTIAL_PROFILES,
        MODEL_SPECIFIC
    )

    /**
     * Kinds whose text is produced at read time and therefore never stored.
     *
     * A write carrying a message for one of these kinds is rejected rather than silently discarded,
     * and a read presents the generated text in place of the absent stored one. Declared here so every
     * surface that has to make that distinction reads one list instead of testing a kind literally.
     */
    val generatedMessageKinds: Set<String> = setOf(SPAWNABLE_AGENTS, CREDENTIAL_PROFILES)

    /**
     * Kinds a role may reference at most once.
     *
     * A second row of one of these kinds would describe the same thing twice and leave the composer to
     * pick arbitrarily, so the role-level rules reject it.
     */
    val singletonKinds: Set<String> = setOf(ROLE, MAIN, SPAWNABLE_AGENTS, CREDENTIAL_PROFILES)
}
